import { createHash } from "node:crypto";
import { execFileSync } from "node:child_process";
import { mkdirSync, readFileSync, writeFileSync } from "node:fs";
import { dirname, relative, resolve, sep } from "node:path";
import { fileURLToPath } from "node:url";

const SDK_ROOT = resolve(dirname(fileURLToPath(import.meta.url)), "..");
const DEFAULT_CONTRACTS_DIR = resolve(SDK_ROOT, "../kuru-contracts-perps");
const CONTRACTS_DIR = resolve(process.env.KURU_CONTRACTS_DIR ?? DEFAULT_CONTRACTS_DIR);
const OUT_DIR = resolve(CONTRACTS_DIR, "out");
const EXPECTED_CONTRACTS_COMMIT = "bdc940e35da8d061c6f541bba6a84eeda10c83e2";
const ALLOW_COMMIT_MISMATCH = process.env.KURU_ALLOW_CONTRACT_COMMIT_MISMATCH === "1";

const contracts = [
  {
    name: "AccountCore",
    exportName: "accountCoreAbi",
    artifact: "AccountCore.sol/AccountCore.json"
  },
  {
    name: "SpotRouter",
    exportName: "spotRouterAbi",
    artifact: "SpotRouter.sol/SpotRouter.json"
  },
  {
    name: "SpotEngine",
    exportName: "spotEngineAbi",
    artifact: "SpotEngine.sol/SpotEngine.json"
  },
  {
    name: "SpotOrderBook",
    exportName: "spotOrderBookAbi",
    artifact: "SpotOrderBook.sol/SpotOrderBook.json"
  },
  {
    name: "SpotPeriphery",
    exportName: "spotPeripheryAbi",
    artifact: "SpotPeriphery.sol/SpotPeriphery.json"
  },
  {
    name: "KuruIntentExecutor",
    exportName: "kuruIntentExecutorAbi",
    artifact: "KuruIntentExecutor.sol/KuruIntentExecutor.json"
  },
  {
    name: "IERC20Metadata",
    exportName: "erc20MetadataAbi",
    artifact: "IERC20Metadata.sol/IERC20Metadata.json"
  }
];

const forbiddenArtifactPattern = /(\.t\.sol\/|Test|Mock|Harness|Bench)/u;

function readJson(path) {
  return JSON.parse(readFileSync(path, "utf8"));
}

function stableStringify(value) {
  if (Array.isArray(value)) {
    return `[${value.map((item) => stableStringify(item)).join(",")}]`;
  }

  if (value && typeof value === "object") {
    return `{${Object.keys(value)
      .sort()
      .map((key) => `${JSON.stringify(key)}:${stableStringify(value[key])}`)
      .join(",")}}`;
  }

  return JSON.stringify(value);
}

function sha256(value) {
  return createHash("sha256").update(value).digest("hex");
}

function portablePath(path) {
  const relativePath = relative(SDK_ROOT, path);
  return (relativePath || ".").split(sep).join("/");
}

function getContractsCommit() {
  return execFileSync("git", ["-C", CONTRACTS_DIR, "rev-parse", "HEAD"], {
    encoding: "utf8"
  }).trim();
}

function assertContractsCommit() {
  const actual = getContractsCommit();
  if (actual !== EXPECTED_CONTRACTS_COMMIT && !ALLOW_COMMIT_MISMATCH) {
    throw new Error(
      [
        `Contract checkout commit mismatch.`,
        `Expected: ${EXPECTED_CONTRACTS_COMMIT}`,
        `Actual:   ${actual}`,
        `Set KURU_ALLOW_CONTRACT_COMMIT_MISMATCH=1 only when intentionally regenerating for a new contract commit.`
      ].join("\n")
    );
  }
  return actual;
}

function loadArtifact(contract) {
  if (forbiddenArtifactPattern.test(contract.artifact) || forbiddenArtifactPattern.test(contract.name)) {
    throw new Error(`Refusing to generate SDK ABI from non-production artifact: ${contract.artifact}`);
  }

  const artifactPath = resolve(OUT_DIR, contract.artifact);
  const artifact = readJson(artifactPath);
  if (!Array.isArray(artifact.abi)) {
    throw new Error(`Artifact is missing an ABI array: ${artifactPath}`);
  }

  return {
    ...contract,
    artifactPath,
    abi: artifact.abi,
    abiSha256: sha256(stableStringify(artifact.abi))
  };
}

function writeIfChanged(path, contents) {
  mkdirSync(dirname(path), { recursive: true });
  try {
    if (readFileSync(path, "utf8") === contents) return;
  } catch {
    // File does not exist yet.
  }
  writeFileSync(path, contents);
}

function renderAbiFile(artifacts) {
  const exports = artifacts
    .map((artifact) => {
      const json = JSON.stringify(artifact.abi, null, 2);
      return `export const ${artifact.exportName} = ${json} as const satisfies Abi;`;
    })
    .join("\n\n");

  const contractAbiEntries = artifacts
    .map((artifact) => `  ${artifact.name}: ${artifact.exportName}`)
    .join(",\n");

  const errorAbiItems = artifacts.flatMap((artifact) =>
    artifact.abi.filter((item) => item && item.type === "error")
  );

  return `// This file is generated by scripts/generate-contracts.mjs. Do not edit by hand.
import type { Abi } from "viem";

${exports}

export const contractAbis = {
${contractAbiEntries}
} as const;

export const kuruErrorAbi = ${JSON.stringify(errorAbiItems, null, 2)} as const satisfies Abi;

export type ContractName = keyof typeof contractAbis;
`;
}

function renderMetadataFile(artifacts, commit) {
  const metadata = {
    contractsCommit: commit,
    expectedContractsCommit: EXPECTED_CONTRACTS_COMMIT,
    contractsDir: portablePath(CONTRACTS_DIR),
    artifactRoot: portablePath(OUT_DIR),
    artifacts: Object.fromEntries(
      artifacts.map((artifact) => [
        artifact.name,
        {
          artifact: artifact.artifact,
          abiSha256: artifact.abiSha256
        }
      ])
    )
  };

  return `// This file is generated by scripts/generate-contracts.mjs. Do not edit by hand.
export const contractMetadata = ${JSON.stringify(metadata, null, 2)} as const;
`;
}

function renderIndexFile(artifacts) {
  const abiExports = artifacts
    .map((artifact) => `  ${artifact.exportName},`)
    .join("\n");

  return `// This file is generated by scripts/generate-contracts.mjs. Do not edit by hand.
export {
${abiExports}
  contractAbis,
  kuruErrorAbi
} from "./abis";
export type { ContractName } from "./abis";
export { contractMetadata } from "./metadata";
`;
}

function main() {
  const commit = assertContractsCommit();
  const artifacts = contracts.map(loadArtifact);

  writeIfChanged(resolve(SDK_ROOT, "src/generated/abis.ts"), renderAbiFile(artifacts));
  writeIfChanged(resolve(SDK_ROOT, "src/generated/metadata.ts"), renderMetadataFile(artifacts, commit));
  writeIfChanged(resolve(SDK_ROOT, "src/generated/index.ts"), renderIndexFile(artifacts));

  console.log(`Generated ${artifacts.length} ABI exports from ${commit}.`);
}

main();
